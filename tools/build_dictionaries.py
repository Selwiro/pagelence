#!/usr/bin/env python3
"""Build the shipped offline dictionary from the full ECDICT table.

The app ships `content/third-party/dictionaries/ecdict.json`, a **general core
dictionary** rather than a per-book glossary. It contains:

* every ECDICT headword that is common enough to be worth carrying on its own:
  BNC/COCA rank <= `--core-rank` (default 30000), any exam tag, Oxford 3000, or
  a CEFR-J/Octanove level;
* every word form in the bundled books (including proper nouns and compounds
  that only a book needs), plus the lemmas those forms point at.

The full upstream table (~66 MB, 770k rows) is not in the repository; pass it
in:

    python3 tools/build_dictionaries.py --ecdict-csv /path/to/ecdict.csv

The pinned upstream revision is `39cfb96` (see THIRD_PARTY_NOTICES.md). Every
entry keeps the Chinese `translation` lines as `senses` and the English
`definition` lines as `en`, so the reader can show either language without a
second table. Bracketed corpus/domain tags such as `[网络]` and `[计]` are
dropped, matching the earlier per-book dictionary.

Morphology is recorded the same way as before: `lemma` comes from ECDICT's
`exchange` column (`0:lemma` on an inflected row, or a base row listing the form
under `s/p/d/i/3/r/t`), and `form` keeps the `1:` marker (`s`, `pd`, `r`, …).
The base row is included even when it never appears in a book (`daisies` →
`daisy`).

Output is compact JSON because the file is an app asset, not an editing source.
`--check` compares the generated bytes with the file on disk.
"""

from __future__ import annotations

import argparse
import csv
import json
import re
import sys
from pathlib import Path

ANDROID = Path(__file__).resolve().parents[1]
CONTENT = ANDROID / "content"
BOOKS = CONTENT / "books"
LEVELS = CONTENT / "third-party" / "word-levels.json"
OUTPUT = CONTENT / "third-party" / "dictionaries" / "ecdict.json"
EXTRA = ANDROID / "content-src" / "extra.json"
OVERRIDES = ANDROID / "content-src" / "core-overrides.json"

WORD = re.compile(r"[A-Za-z][A-Za-z'’\-]*")
# A core headword or inflected form: one token, letters with apostrophe, hyphen
# or period (`m.d.`), no spaces or digits.
CORE_WORD = re.compile(r"[a-z][a-z'.\-]*")
# A book phrase that upstream may also carry (`west country`); sentences and
# long hint targets are rejected by the word-count check.
BOOK_PHRASE = re.compile(r"[a-z][a-z'.\- ]*")
POS = re.compile(r"^(n|v|vt|vi|adj|adv|a|ad|prep|pron|conj|art|num|int|aux|abbr|pl)\.")
POS_ALIAS = {"a": "adj.", "ad": "adv."}
KIND = re.compile(r"[0-9spdi3rt]")
BASE_KINDS = {"s", "p", "d", "i", "3", "r", "t"}

# ECDICT has no `0:` row for a few irregular forms of `be`, and `does` points at
# `doe` (the female deer) instead of the auxiliary. Override only these.
LEMMA_OVERRIDES = {
    "am": "be",
    "are": "be",
    "was": "be",
    "does": "do",
}

# One-word lemmas only; phrases, possessives and upstream typos are rejected.
LEMMA = re.compile(r"[a-z][a-z'’\-]*")


def normalize(term: str) -> str:
    return term.strip().lower().replace("’", "'")


def to_rank(value: str) -> int:
    try:
        return int(value)
    except (TypeError, ValueError):
        return 0


def load_levels() -> set[str]:
    """Words with a CEFR-J/Octanove level (`list` layer) only.

    Inferred levels (`aligned`/`derived`/`tag`/`freq`) are built partly from
    this dictionary, so including them here would make the two builds chase
    each other. The core dictionary stays keyed to the curated word lists.
    """
    if not LEVELS.is_file():
        return set()
    data = json.loads(LEVELS.read_text(encoding="utf-8"))
    sources = data.get("sources") or {}
    words = set()
    for word in data.get("levels", {}):
        slots = sources.get(word) or {}
        if not sources or "list" in slots.values():
            words.add(normalize(word))
    return words


def book_forms() -> set[str]:
    """Every word form the bundled books need, including proper nouns.

    Skeleton units have no `sentences` yet, so the paragraph text is the source
    of truth; sentence and hint forms are added on top for phrases and context.
    """
    forms: set[str] = set()
    for path in sorted(BOOKS.glob("*/book.json")):
        book = json.loads(path.read_text(encoding="utf-8"))
        for chapter in book.get("chapters", []):
            for unit in chapter.get("units", []):
                for paragraph in unit.get("paragraphs", []):
                    for match in WORD.findall(paragraph.get("text", "")):
                        forms.add(normalize(match))
                    for sentence in paragraph.get("sentences", []):
                        for match in WORD.findall(sentence.get("text", "")):
                            forms.add(normalize(match))
                    for hint in paragraph.get("hints", []):
                        if hint.get("target"):
                            forms.add(normalize(hint["target"]))
                        if hint.get("lemma"):
                            forms.add(normalize(hint["lemma"]))
    return forms


def exchange_parts(row: dict[str, str]) -> list[tuple[str, str]]:
    """`exchange` as `(kind, form)` pairs; malformed chunks are skipped."""
    parts: list[tuple[str, str]] = []
    for chunk in (row.get("exchange") or "").split("/"):
        kind, _, form = chunk.partition(":")
        form = normalize(form)
        if kind.strip() and form and KIND.fullmatch(kind.strip()):
            parts.append((kind.strip(), form))
    return parts


def split_lines(value: str) -> list[str]:
    """Split one ECDICT cell into lines, dropping bracketed corpus tags."""
    lines = [line.strip() for line in value.replace("\\r", "").split("\\n")]
    return [
        line for line in lines
        if line and not line.startswith("[") and not line.startswith("【")
    ]


# Mid-line corpus/domain tags (`art. [计] 累加器…`). A bracketed regional or
# encyclopaedic note (`亚琛[德国城市]`) is longer and stays.
DOMAIN_TAG = re.compile(
    r"[\[【]\s*(?:计|网络|医|化|经|军|植|动|法|数|物理|电子|计算机|生物|地质|冶|机|电|"
    r"通信|体育|音乐|美术|心理|哲|宗|农|林|水产|航海|航空|石油|建|纺|食|药|病|解剖|统计|"
    r"天|气象|环保|能源|汽车|铁路|戏曲|逻辑|修辞|矿|印|服装|烹饪|圣经|中医|西医|兽医|"
    r"昆虫|细菌|病毒|免疫|遗传|生态|地理|历史|考古|军事|经济|会计|金融|贸易|管理|营销|"
    r"法律|政治|外交|新闻|出版|广播|电视|电影|摄影|绘画|雕塑|建筑|舞蹈|戏剧|棋|牌|游戏|"
    r"编程|软件|硬件|数据库|电工|机械|土木|水利|测绘|化工|材料|天然气|纺织|轻工|食品|"
    r"酿造|烟草|医药|护理|生理|病理|药理|教育|宗教|神话)\s*[\]】]\s*",
)

NOTE_BODY = (
    r"(?:[a-z'’\-]+的(?:现在时|过去式|过去分词|现在分词|第三人称单数|名词复数|复数|比较级|最高级)(?:和(?:过去式|过去分词|现在分词|名词复数|复数))?"
    r"|[a-z'’\-]+复数|名词复数|动词复数|形容词复数|复数形式)"
)
NOTE_LINE = re.compile(r"^\s*[（(]?" + NOTE_BODY + r"[）)]?\s*$", re.IGNORECASE)
NOTE_PAREN = re.compile(r"[（(][^）)]*" + NOTE_BODY + r"[^）)]*[）)]", re.IGNORECASE)


def clean_definition(value: str) -> str:
    """Drop a form note that is the whole line, or only its parenthesis."""
    text = DOMAIN_TAG.sub(" ", value)
    text = NOTE_PAREN.sub(" ", text)
    text = re.sub(r"\s+", " ", text).strip(" ,，;；")
    if not text or NOTE_LINE.match(value):
        return ""
    return text


def senses(lines: list[str]) -> list[list[str]]:
    out: list[list[str]] = []
    for line in lines:
        match = POS.match(line)
        if match:
            pos = match.group(1) + "."
            definition = clean_definition(line[match.end():].strip())
            if definition:
                out.append([POS_ALIAS.get(match.group(1), pos), definition])
        else:
            definition = clean_definition(line)
            if definition:
                out.append(["", definition])
    return out


def load_extra() -> dict[str, dict]:
    if not EXTRA.is_file():
        return {}
    data = json.loads(EXTRA.read_text(encoding="utf-8"))
    return data.get("entries") or {}


def load_overrides() -> dict[str, dict]:
    if not OVERRIDES.is_file():
        return {}
    data = json.loads(OVERRIDES.read_text(encoding="utf-8"))
    return data.get("entries") or {}


def apply_overrides(entries: dict[str, dict]) -> None:
    """Replace the first senses of the curated high-frequency words.

    ECDICT orders homographs by its own editorial history, so `may` starts with
    the month and `can` with a tin. Those are the words a reader is most likely
    to tap, and the first sense is what the word card stores; the overrides are
    deliberately short and grammar-shaped.
    """
    for term, source in load_overrides().items():
        key = normalize(term)
        entry = entries.get(key)
        if entry is None:
            raise SystemExit(f"core-overrides.json: {term} is not in ECDICT")
        for field in ("senses", "en"):
            value = source.get(field)
            if value is None:
                continue
            cleaned = []
            for pair in value:
                if not isinstance(pair, list) or len(pair) != 2:
                    raise SystemExit(f"core-overrides.json: {term}.{field} must be [[pos, text], …]")
                pos, definition = str(pair[0]).strip(), str(pair[1]).strip()
                if not definition:
                    raise SystemExit(f"core-overrides.json: {term}.{field} has an empty definition")
                cleaned.append([pos, definition])
            entry[field] = cleaned


def is_core(term: str, row: dict[str, str], levels: set[str], core_rank: int) -> bool:
    frq = to_rank(row.get("frq", ""))
    bnc = to_rank(row.get("bnc", ""))
    return (
        (0 < frq <= core_rank)
        or (0 < bnc <= core_rank)
        or bool((row.get("tag") or "").strip())
        or (row.get("oxford") or "").strip() not in ("", "0")
        or term in levels
    )


def build(csv_path: Path, core_rank: int) -> tuple[dict, dict]:
    wanted = book_forms()
    levels = load_levels()

    # Pass 1: pick candidate headwords. Core words are single tokens; a book
    # phrase is kept only when it is short enough to be an upstream entry.
    candidates: dict[str, dict[str, str]] = {}
    with csv_path.open(encoding="utf-8-sig", newline="") as source:
        for row in csv.DictReader(source):
            term = normalize(row["word"])
            if not term or term in candidates:
                continue
            core = is_core(term, row, levels, core_rank)
            book = term in wanted
            if not (core or book):
                continue
            if core and not CORE_WORD.fullmatch(term):
                continue
            if book and not CORE_WORD.fullmatch(term):
                if not BOOK_PHRASE.fullmatch(term) or len(term.split()) > 4:
                    continue
            candidates[term] = row

    # Pass 2: morphology for every candidate. A candidate that is an inflected
    # form may point at a base row that is not itself a candidate yet; record
    # that base so pass 3 can load its definitions.
    own_lemma: dict[str, str] = {}
    base_forms: dict[str, str] = {}
    form_kind: dict[str, str] = {}
    lemma_terms: set[str] = set()
    with csv_path.open(encoding="utf-8-sig", newline="") as source:
        for row in csv.DictReader(source):
            term = normalize(row["word"])
            parts = exchange_parts(row)
            if term in candidates:
                for kind, form in parts:
                    if kind == "0":
                        own_lemma[term] = form
                        lemma_terms.add(form)
                    elif kind == "1":
                        form_kind[term] = form
            for kind, form in parts:
                if kind in BASE_KINDS and form in candidates and form != term:
                    base_forms.setdefault(form, term)
                    lemma_terms.add(term)

    needed = set(candidates) | lemma_terms | set(base_forms.values()) | set(own_lemma.values())

    # Pass 3: load the rows we will actually serialize.
    rows: dict[str, dict[str, str]] = {}
    with csv_path.open(encoding="utf-8-sig", newline="") as source:
        for row in csv.DictReader(source):
            term = normalize(row["word"])
            if term in needed and term not in rows:
                rows[term] = row

    # Definition-bearing terms only. A lemma that upstream has no definition
    # for is not worth a pointer that the reader cannot follow.
    defined: dict[str, tuple[list[list[str]], list[list[str]], dict[str, str]]] = {}
    for term, row in rows.items():
        zh = senses(split_lines(row.get("translation") or ""))
        en = senses(split_lines(row.get("definition") or ""))
        if zh or en:
            defined[term] = (zh, en, row)

    lemma_of: dict[str, str] = {}
    for term in candidates:
        lemma = own_lemma.get(term) or base_forms.get(term)
        if valid_lemma(lemma) and lemma != term and lemma in defined:
            lemma_of[term] = lemma
    for term, lemma in LEMMA_OVERRIDES.items():
        if term in defined and valid_lemma(lemma) and lemma in defined:
            lemma_of[term] = lemma

    entries: dict[str, dict] = {}
    for term in sorted(defined):
        zh, en, row = defined[term]
        entry: dict = {}
        phonetic = (row.get("phonetic") or "").strip()
        if phonetic:
            entry["phonetic"] = phonetic
        if term in lemma_of:
            entry["lemma"] = lemma_of[term]
        if term in form_kind:
            entry["form"] = form_kind[term]
        if zh:
            entry["senses"] = zh
        if en:
            entry["en"] = en
        tag = " ".join((row.get("tag") or "").split())
        if tag:
            entry["tag"] = tag
        entries[term] = entry

    apply_overrides(entries)

    # A book-only name can have a pronunciation but no lexical definition
    # (`Alice`); keep the phonetic so tapping the name still shows it.
    for term, row in rows.items():
        if term in entries or term not in wanted:
            continue
        phonetic = (row.get("phonetic") or "").strip()
        if phonetic:
            entries[term] = {"phonetic": phonetic}

    # `extra.json` only carries proper-name recognition (kind) and a note;
    # dialect and coinages stay in the book package, not here.
    for term, source in load_extra().items():
        key = normalize(term)
        if key in entries:
            raise SystemExit(f"extra.json: {term} already exists in ECDICT")
        entry = {}
        if source.get("phonetic"):
            entry["phonetic"] = source["phonetic"]
        if source.get("kind"):
            entry["kind"] = source["kind"]
        if source.get("note"):
            entry["note"] = source["note"]
        entries[key] = entry

    payload = {
        "schemaVersion": 4,
        "id": "ecdict",
        "termCount": len(entries),
        "source": (
            "ECDICT 39cfb96: core headwords by BNC/COCA rank <= %d, exam tags, "
            "Oxford 3000 and CEFR-J/Octanove levels, plus every form used by the "
            "bundled books and the lemmas those forms point at" % core_rank
        ),
        "entries": entries,
    }
    return payload, {
        "book_forms": wanted,
        "candidates": len(candidates),
        "defined": len(defined),
        "lemmas": len(lemma_of),
    }


def valid_lemma(form: str | None) -> bool:
    return bool(form) and LEMMA.fullmatch(form) is not None


def serialize(payload: dict) -> str:
    return json.dumps(payload, ensure_ascii=False, separators=(",", ":")) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--ecdict-csv", type=Path, required=True)
    parser.add_argument(
        "--core-rank",
        type=int,
        default=30000,
        help="keep ECDICT headwords with BNC or COCA rank <= this (default 30000)",
    )
    parser.add_argument("--check", action="store_true", help="verify the generated file is current")
    args = parser.parse_args()

    if not args.ecdict_csv.is_file():
        parser.error(f"ECDICT CSV not found: {args.ecdict_csv}")

    payload, stats = build(args.ecdict_csv, args.core_rank)
    text = serialize(payload)
    size_mib = len(text.encode("utf-8")) / 1048576
    missing = sorted(
        term for term in stats["book_forms"]
        if CORE_WORD.fullmatch(term) and term not in payload["entries"]
    )
    print(
        f"book forms: {len(stats['book_forms'])}  candidates: {stats['candidates']}  "
        f"entries: {len(payload['entries'])}  lemmas: {stats['lemmas']}  "
        f"size: {size_mib:.1f} MiB  missing book words: {len(missing)}"
    )
    if missing:
        print("missing sample:", ", ".join(missing[:40]))

    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != text:
            print(f"stale: {OUTPUT.relative_to(ANDROID.parent.parent)}")
            sys.exit(1)
        print("up to date")
        return

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT} ({OUTPUT.stat().st_size / 1048576:.1f} MiB)")


if __name__ == "__main__":
    main()
